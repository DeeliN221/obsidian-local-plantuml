#!/usr/bin/env node
/**
 * Inline the engine, its layout runtime, the theme table and the whole standard
 * library into a generated TypeScript module.
 *
 * The Obsidian community installer only downloads `main.js`, `manifest.json`
 * and `styles.css` from a release, so a plugin that reads sibling files from
 * its own directory cannot work there. Everything the engine needs at runtime
 * therefore ships inside `main.js`; the standard library stays a name -> source
 * map and is evaluated only when a diagram references it.
 */

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const engineDir = join(here, '../node_modules/@plantuml/core')
const stdlibDir = join(here, '../stdlib')
const outFile = join(here, '../src/generated/assets.js')
const typesFile = join(here, '../src/generated/assets.d.ts')

const viz = await readFile(join(engineDir, 'viz-global.js'), 'utf8')
const themes = await readFile(join(engineDir, 'themes.js'), 'utf8')

/** @type {Record<string, string>} */
const stdlib = {}
for (const name of (await readdir(stdlibDir)).sort()) {
  if (!name.endsWith('.js')) continue
  stdlib[name] = await readFile(join(stdlibDir, name), 'utf8')
}

const header = `// Generated by scripts/embed-assets.mjs. Do not edit.\n`
const body =
  header +
  `export const VIZ_SOURCE = ${JSON.stringify(viz)}\n` +
  `export const THEMES_SOURCE = ${JSON.stringify(themes)}\n` +
  `export const STDLIB_SOURCES = ${JSON.stringify(stdlib)}\n`

const types = `${header}export declare const VIZ_SOURCE: string\nexport declare const THEMES_SOURCE: string\nexport declare const STDLIB_SOURCES: Record<string, string>\n`

await mkdir(dirname(outFile), { recursive: true })
await writeFile(outFile, body)
await writeFile(typesFile, types)
await writeFile(join(dirname(outFile), 'package.json'), '{"type":"module"}\n')
console.log(
  `assets: ${Object.keys(stdlib).length} stdlib entries, ${(body.length / 1024 / 1024).toFixed(1)} MiB module`,
)
