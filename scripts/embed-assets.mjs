#!/usr/bin/env node
/**
 * Bake the PlantUML theme table into a TypeScript module.
 *
 * `themes.js` is a classic script that assigns `PLANTUML_THEMES` on the global
 * object. Running it here (at build time) and emitting the resulting object as
 * a normal module keeps the plugin free of runtime `eval`, which the Obsidian
 * reviewer rejects.
 */

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const here = dirname(fileURLToPath(import.meta.url))
const source = join(here, '../node_modules/@plantuml/core/themes.js')
const outFile = join(here, '../src/generated/themes.js')

const sandbox = { console }
sandbox.globalThis = sandbox
sandbox.window = sandbox
sandbox.self = sandbox
vm.createContext(sandbox)
vm.runInContext(readFileSync(source, 'utf8'), sandbox)

const themes = sandbox.PLANTUML_THEMES
if (themes === null || typeof themes !== 'object' || Object.keys(themes).length === 0) {
  throw new Error('embed-assets: themes.js did not produce PLANTUML_THEMES')
}

mkdirSync(dirname(outFile), { recursive: true })
const module = `// Generated by scripts/embed-assets.mjs. Do not edit.\nexport const PLANTUML_THEMES = ${JSON.stringify(themes)}\n`
const types = `export declare const PLANTUML_THEMES: Record<string, string>\n`
writeFileSync(join(here, '../src/generated/themes.d.ts'), types)
writeFileSync(join(here, '../src/generated/package.json'), '{"type":"module"}\n')
writeFileSync(outFile, module)

// Viz ships as a UMD file. A .cjs copy makes the bundler treat it as CommonJS
// so the default import is the UMD exports object (with `instance()`); the
// runtime then hands it to the engine as PLANTUML_VIZ.
copyFileSync(join(here, '../node_modules/@plantuml/core/viz-global.js'), join(here, '../src/generated/viz.cjs'))
writeFileSync(
  join(here, '../src/generated/viz.d.cts'),
  `declare const Viz: { instance(): Promise<unknown>; graphvizVersion: string }\nexport default Viz\n`,
)
console.log(`themes: ${Object.keys(themes).length} entries, ${(module.length / 1024).toFixed(0)} KiB`)
